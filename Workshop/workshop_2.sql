CREATE Procedure Sales_proce
@PRODUCTID int
@QTYTOSELL int
as 
BEGIN

    DECLARE @STOCKAVAILABLE INT
    SELECT @STOCKAVAILABLE=[QYT_AVAILABLE]
    FROM PRODUCTS
    WHERE PRODUCTID=@PRODUCTID

    IF (@STOCKAVAILABLE<@QTYTOSELL)
        BEGIN
            RAISERROR('NOT ENOUGH STOCK AVAILABLE',16,1)
        END
    ELSE
        BEGIN   
            BEGIN TRANSACTION
                UPDATE PRODUCTS
                SET QTY_AVAILABLE=(QTY_AVAILABLE-@QTYTOSELL)
                WHERE PRODUCTID=@PRODUCTID
                DECLARE @MAXPRODUCTSALESID INT
                SELECT @MAXPRODUCTSALESID=CASE 
                            WHEN max(PRODUCT_SALES_ID) IS NULL
                            THEN 0  ELSE MAX(PRODUCT_SALES_ID)
                            END
                        FROM PRODUCTS_SALES

                SET @MAXPRODUCTSALESID=@MAXPRODUCTSALESID+1
                INSERT INTO PRODUCTS_SALES VALUES (@MAXPRODUCTSALESID, @PRODUCTID, @QTYTOSELL)
            COMMIT TRANSACTION
        END
END




