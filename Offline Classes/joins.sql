--4 FIND ALL CUSTOMERS AND THEIR ORDERS  (INCLUDE CUSTOMERS WITH NO ORDERS)


SELECT C.CUSTID,O.ORDERID
 FROM CUSTOMERS$ AS C 
LEFT JOIN ORDERS$ AS O
ON C.CUSTID=O.CUSTID


-- 5 FIND ORDERS THAT WERE NOT RETURNED 

