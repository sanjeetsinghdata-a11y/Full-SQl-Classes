---  FIND HOW MANY ORDERS ARE  PLACED IN 2017

SELECT
Region,
COUNT([Order ID]) ORDERPLACED
FROM Orders$
WHERE YEAR([Order Date])='2017'
GROUP BY Region


---- FIND CUSTOMER THOSE WHO HAVE HIGHEST  NUMBERS OF ORDERS  IN EAST


SELECT   [Customer ID],count(*) as total_orders
  FROM
Orders$
where region='east'
GROUP BY  [Customer ID]
HAVING count(*)
=(SELECT max(total_order)
FROM(
    SELECT  
[Customer ID] ,count(*) as total_order
from Orders$
where Region='east'
GROUP BY [Customer ID]
)t 
)

