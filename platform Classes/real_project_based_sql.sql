-- 23. Identify products whose sales decreased
--     significantly after another product from the
--     same category was launched.


with ProductLaunced as (

        SELECT 
        [product id],
        [product name],
        [category],
        min([order date]) as LounchedDate
        FROM Orders$
        GROUP BY [product id],
        [product name],
        [category]

),
OtherProductLounched as (

            SELECT
            p1.[product id],
            p1.[product name],
            p1.[category],
            p1.LounchedDate,
            min(p2.LounchedDate) as  OtherProductLouncedDate
            from ProductLaunced as p1
            JOIN ProductLaunced as p2
            on p1.[category]=p2.[category]
            and p1.[product id]<> p2.[product id]
            and p2.LounchedDate>p1.LounchedDate
            GROUP BY 
            p1.[product id],
            p1.[product name],  
            p1.[category],
            p1.LounchedDate
),
ProductSales as (


    SELECT 
    o.[product id],
    o.[product name],
    o.[category],
    sum(CASE 
        WHEN o.[order date]<opl.OtherProductLouncedDate THEN  o.sales
        else 0
    END) as SalesBefore,

    sum(
        CASE 
            WHEN o.[order date]>=opl.OtherProductLouncedDate THEN  o.sales
            else 0 
        END
    )as SalesAfter
    
    FROM orders$ as o
    JOIN OtherProductLounched as opl
    on o.[product id]=opl.[product id]
    GROUP BY
    o.[product id],
    o.[product name],
    o.category

)

SELECT 
[product id],
[product name],
[category],
SalesBefore,
SalesAfter,
(SalesBefore-SalesAfter)*100.0/nullif(SalesBefore,0) as DecreasedRate
FROM ProductSales
WHERE SalesAfter<SalesBefore*0.80





