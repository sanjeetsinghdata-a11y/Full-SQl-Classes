-- 10. Find products whose return rate is
--     greater than 10%.

SELECT
    o.[Product ID],
    COUNT(DISTINCT o.[Order ID]) AS Total_Orders,
    COUNT(DISTINCT CASE
        WHEN r.[Order ID] IS NOT NULL THEN o.[Order ID]
    END) AS Returned_Orders,

    CAST(
        COUNT(DISTINCT CASE
            WHEN r.[Order ID] IS NOT NULL THEN o.[Order ID]
        END) * 100.0
        / COUNT(DISTINCT o.[Order ID])
        AS DECIMAL(10,2)
    ) AS Return_Rate

FROM Orders$ o

LEFT JOIN Returns$ r
    ON o.[Order ID] = r.[Order ID]

GROUP BY o.[Product ID]

HAVING
    COUNT(DISTINCT CASE
        WHEN r.[Order ID] IS NOT NULL THEN o.[Order ID]
    END) * 100.0
    / COUNT(DISTINCT o.[Order ID]) > 10;




-- 11. Find customers whose order value increased
--     for 3 consecutive orders and then decreased.

with ct1 as (


    SELECT [Customer ID],[Customer Name],[Order ID],[Order Date],sum(sales) as totalordersales
    FROM  Orders$
    GROUP BY  [Customer ID],[Customer Name],[Order ID],[Order Date]
),

ct2 as (

    SELECT [Customer ID],[Customer Name],[Order Date],totalordersales ,
    LAG(totalordersales,1) OVER(PARTITION BY [Customer ID] ORDER BY [Order Date]) as prevOrder1,
    LAG(totalordersales,2) OVER(PARTITION BY [Customer ID] ORDER BY [Order Date]) as prevOrder2,
    LAG(totalordersales,3) OVER(PARTITION BY [Customer ID] ORDER BY [Order Date]) as prevOrder3
    FROM ct1

)
,ct3 as (

    SELECT *,
    lead(totalordersales,1) OVER(
        PARTITION BY [Customer ID] ORDER BY [Order Date]
    )as nextorder
    FROM ct2

)
,
ct4 as(

    SELECT *,
    CASE 
        WHEN prevOrder1<prevOrder2
        AND prevOrder2<prevOrder3
        and totalordersales>nextorder
        THEN  1
        ELSE  0
    END as INcreasing    
    FROM  ct3

)

SELECT * FROM ct4
WHERE INcreasing=1
AND totalordersales>nextorder






