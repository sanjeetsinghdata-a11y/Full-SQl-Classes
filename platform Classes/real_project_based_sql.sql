-- 25. Executive-level monthly sales report
--     Revenue
--     Profit
--     Profit Margin
--     Number of Orders
--     Number of Customers
--     Average Order Value
--     New Customers
--     Returning Customers
--     Return Rate
--     MoM Revenue Growth
--     YoY Revenue Growth


WITH MonthlySales AS
(
    SELECT
        DATEFROMPARTS(
            YEAR([Order Date]),
            MONTH([Order Date]),
            1
        ) AS Month,

        SUM(Sales) AS Revenue,
        SUM(Profit) AS Profit,

        COUNT(DISTINCT [Order ID]) AS Number_of_Orders,

        COUNT(DISTINCT [Customer ID]) AS Number_of_Customers

    FROM Orders$

    GROUP BY
        DATEFROMPARTS(
            YEAR([Order Date]),
            MONTH([Order Date]),
            1
        )
),

MonthlyMargin AS
(
    SELECT
        Month,
        Revenue,
        Profit,
        Number_of_Orders,
        Number_of_Customers,

        Profit * 100.0 / NULLIF(Revenue, 0)
            AS Profit_Margin,

        Revenue * 1.0 / NULLIF(Number_of_Orders, 0)
            AS Average_Order_Value

    FROM MonthlySales
),

CustomerFirstPurchase AS
(
    SELECT
        [Customer ID],
        MIN(
            DATEFROMPARTS(
                YEAR([Order Date]),
                MONTH([Order Date]),
                1
            )
        ) AS FirstPurchaseMonth

    FROM Orders$

    GROUP BY [Customer ID]
),

MonthlyCustomerStatus AS
(
    SELECT
        DATEFROMPARTS(
            YEAR(o.[Order Date]),
            MONTH(o.[Order Date]),
            1
        ) AS Month,

        COUNT(DISTINCT
            CASE
                WHEN cf.FirstPurchaseMonth =
                     DATEFROMPARTS(
                         YEAR(o.[Order Date]),
                         MONTH(o.[Order Date]),
                         1
                     )
                THEN o.[Customer ID]
            END
        ) AS New_Customers,

        COUNT(DISTINCT
            CASE
                WHEN cf.FirstPurchaseMonth <
                     DATEFROMPARTS(
                         YEAR(o.[Order Date]),
                         MONTH(o.[Order Date]),
                         1
                     )
                THEN o.[Customer ID]
            END
        ) AS Returning_Customers

    FROM Orders$ o

    INNER JOIN CustomerFirstPurchase cf
        ON o.[Customer ID] = cf.[Customer ID]

    GROUP BY
        DATEFROMPARTS(
            YEAR(o.[Order Date]),
            MONTH(o.[Order Date]),
            1
        )
),

MonthlyReturns AS
(
    SELECT
        DATEFROMPARTS(
            YEAR(o.[Order Date]),
            MONTH(o.[Order Date]),
            1
        ) AS Month,

        COUNT(DISTINCT
            CASE
                WHEN r.[Order ID] IS NOT NULL
                THEN o.[Order ID]
            END
        ) AS Returned_Orders

    FROM Orders$ o

    LEFT JOIN Returns$ r
        ON o.[Order ID] = r.[Order ID]

    GROUP BY
        DATEFROMPARTS(
            YEAR(o.[Order Date]),
            MONTH(o.[Order Date]),
            1
        )
),

FinalReport AS
(
    SELECT
        m.Month,
        m.Revenue,
        m.Profit,
        m.Profit_Margin,
        m.Number_of_Orders,
        m.Number_of_Customers,
        m.Average_Order_Value,

        c.New_Customers,
        c.Returning_Customers,

        r.Returned_Orders * 100.0
            / NULLIF(m.Number_of_Orders, 0)
            AS Return_Rate,

        LAG(m.Revenue, 1) OVER (
            ORDER BY m.Month
        ) AS Previous_Month_Revenue,

        LAG(m.Revenue, 12) OVER (
            ORDER BY m.Month
        ) AS Previous_Year_Revenue

    FROM MonthlyMargin m

    LEFT JOIN MonthlyCustomerStatus c
        ON m.Month = c.Month

    LEFT JOIN MonthlyReturns r
        ON m.Month = r.Month
)

SELECT
    Month,
    Revenue,
    Profit,
    Profit_Margin,
    Number_of_Orders,
    Number_of_Customers,
    Average_Order_Value,
    New_Customers,
    Returning_Customers,
    Return_Rate,

    (Revenue - Previous_Month_Revenue) * 100.0
        / NULLIF(Previous_Month_Revenue, 0)
        AS MoM_Revenue_Growth,

    (Revenue - Previous_Year_Revenue) * 100.0
        / NULLIF(Previous_Year_Revenue, 0)
        AS YoY_Revenue_Growth

FROM FinalReport

ORDER BY Month;


  
 