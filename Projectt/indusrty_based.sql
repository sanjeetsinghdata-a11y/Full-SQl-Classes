 -- Calculate the customer retention rate for each year.
-- Business use: Measures how effectively the company retains customers.

with ct1 as(

        SELECT DISTINCT
        [customer id],
        year([order OrderDate]) as orderyear
        FROM orders$$

),
ct2 as (

        SELECT orderyear,
        count(*) as totalcustomers
         FROM ct1
         GROUP BY orderyear


),
ct3 as (

            SELECT 
            curr.orderyear,
            count(*) as  RetainedCustomer
            FROM ct1 as curr
            JOIN ct1 as prev
            on curr.[customer id]=prev.[customer id]
            and curr.orderyear=prev.orderyear+1
            GROUP BY curr.orderyear

)
 
SELECT 
c.orderyear,
p.totalcustomers as previouyearcustomer,
coalesce(r.RetainedCustomers,0) as RetainedCustomers,
CAST(
    coalesce(r.RetainedCustomers,0)*100.0
    / nullif(p.totalcustomers,0) as Decimal(5,2)
) as Retentionrate
FROM ct2 as c
JOIN ct2 as p
ON c.orderyear=p.orderyear+1
LEFT JOIN ct3 as r
on c.orderyear=r.orderyear
ORDER BY c.orderyear






WITH ct1 AS (
    -- Get unique customer-year combinations
    SELECT DISTINCT
        [Customer ID],
        YEAR([Order OrderDate]) AS OrderYear
    FROM [Orders$]
),
ct2 AS (
    -- Count customers active in each year
    SELECT
        OrderYear,
        COUNT(*) AS TotalCustomers
    FROM ct1
    GROUP BY OrderYear
),
ct3 AS (
    -- Count previous-year customers who returned this year
    SELECT
        curr.OrderYear,
        COUNT(*) AS RetainedCustomers
    FROM ct1 AS curr
    INNER JOIN ct1 AS prev
        ON curr.[Customer ID] = prev.[Customer ID]
        AND curr.OrderYear = prev.OrderYear + 1
    GROUP BY curr.OrderYear
)


SELECT
    c.OrderYear,
    p.TotalCustomers AS PreviousYearCustomers,
    COALESCE(r.RetainedCustomers, 0) AS RetainedCustomers,
    CAST(
        COALESCE(r.RetainedCustomers, 0) * 100.0
        / NULLIF(p.TotalCustomers, 0)
        AS DECIMAL(5, 2)
    ) AS RetentionRate
FROM ct2 AS c
INNER JOIN ct2 AS p
    ON c.OrderYear = p.OrderYear + 1
LEFT JOIN ct3 AS r
    ON c.OrderYear = r.OrderYear
ORDER BY c.OrderYear;


